-- TaskBuddy first-version schema for Oracle 19c.
-- Run with setup_database.py or SQL Developer using your team's Oracle account.
-- All TIMESTAMP values written by the backend use UTC.
-- TB_ prefixes keep these project tables separate from unrelated course tables.

CREATE TABLE tb_users (
    user_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    username VARCHAR2(40 CHAR) NOT NULL,
    username_key VARCHAR2(40 CHAR) NOT NULL UNIQUE,
    email VARCHAR2(254 CHAR) NOT NULL,
    password_hash VARCHAR2(512 CHAR) NOT NULL,
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE tb_tasks (
    task_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    user_id NUMBER NOT NULL REFERENCES tb_users(user_id) ON DELETE CASCADE,
    title VARCHAR2(200 CHAR) NOT NULL,
    description CLOB,
    is_pinned NUMBER(1) DEFAULT 0 NOT NULL CHECK (is_pinned IN (0, 1)),
    is_hidden NUMBER(1) DEFAULT 0 NOT NULL CHECK (is_hidden IN (0, 1)),
    is_deleted NUMBER(1) DEFAULT 0 NOT NULL CHECK (is_deleted IN (0, 1)),
    is_completed NUMBER(1) DEFAULT 0 NOT NULL CHECK (is_completed IN (0, 1)),
    deleted_at TIMESTAMP,
    expires_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL
);

CREATE INDEX tb_tasks_user_idx ON tb_tasks(user_id, is_deleted, is_hidden);

CREATE TABLE tb_sessions (
    token_hash VARCHAR2(64 CHAR) PRIMARY KEY,
    user_id NUMBER NOT NULL REFERENCES tb_users(user_id) ON DELETE CASCADE,
    expires_at TIMESTAMP NOT NULL
);

CREATE INDEX tb_sessions_user_idx ON tb_sessions(user_id);

CREATE TABLE tb_subtasks (
    subtask_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    task_id NUMBER NOT NULL REFERENCES tb_tasks(task_id) ON DELETE CASCADE,
    title VARCHAR2(200 CHAR) NOT NULL,
    order_position NUMBER DEFAULT 0 NOT NULL,
    is_completed NUMBER(1) DEFAULT 0 NOT NULL CHECK (is_completed IN (0, 1))
);

CREATE TABLE tb_reminders (
    reminder_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    task_id NUMBER UNIQUE REFERENCES tb_tasks(task_id) ON DELETE CASCADE,
    subtask_id NUMBER UNIQUE REFERENCES tb_subtasks(subtask_id) ON DELETE CASCADE,
    reminder_date TIMESTAMP NOT NULL,
    email VARCHAR2(254 CHAR) NOT NULL,
    is_sent NUMBER(1) DEFAULT 0 NOT NULL CHECK (is_sent IN (0, 1)),
    CONSTRAINT tb_reminder_parent_ck CHECK (
        (task_id IS NOT NULL AND subtask_id IS NULL) OR
        (task_id IS NULL AND subtask_id IS NOT NULL)
    )
);
