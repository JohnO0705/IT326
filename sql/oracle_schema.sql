-- TaskBuddy first-version schema for Oracle 19c.
-- Run with setup_database.py or SQL Developer using your team's Oracle account.
-- All TIMESTAMP values written by the backend use UTC.
-- TB_ prefixes keep these project tables separate from unrelated course tables.

CREATE TABLE tb_users (
    user_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    username VARCHAR2(40 CHAR) NOT NULL,
    username_key VARCHAR2(40 CHAR) NOT NULL,
    email VARCHAR2(254 CHAR) NOT NULL,
    password_hash VARCHAR2(512 CHAR) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    security_question VARCHAR2(200 CHAR),
	security_answer_hash VARCHAR2(512 CHAR),
	PRIMARY KEY (user_id),
	UNIQUE (username_key)
);

CREATE TABLE tb_tasks (
    task_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    user_id INTEGER NOT NULL,
    title VARCHAR2(200 CHAR) NOT NULL,
    description CLOB,
    is_pinned SMALLINT DEFAULT '0' NOT NULL,
    is_hidden SMALLINT DEFAULT '0' NOT NULL,
    is_deleted SMALLINT DEFAULT '0' NOT NULL,
    is_completed SMALLINT DEFAULT '0' NOT NULL,
    deleted_at TIMESTAMP,
    expires_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    PRIMARY KEY (task_id),
	FOREIGN KEY(user_id) REFERENCES tb_users (user_id) ON DELETE CASCADE,
	CHECK (is_pinned IN (0, 1)),
	CHECK (is_hidden IN (0, 1)),
	CHECK (is_deleted IN (0, 1)),
	CHECK (is_completed IN (0, 1))
);

CREATE INDEX tb_tasks_user_idx ON tb_tasks(user_id, is_deleted, is_hidden);

CREATE TABLE tb_sessions (
    token_hash VARCHAR2(64 CHAR) PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES tb_users(user_id) ON DELETE CASCADE,
    expires_at TIMESTAMP NOT NULL,
    PRIMARY KEY (token_hash),
	FOREIGN KEY(user_id) REFERENCES tb_users (user_id) ON DELETE CASCADE
);

CREATE INDEX tb_sessions_user_idx ON tb_sessions(user_id);

CREATE TABLE tb_subtasks (
    subtask_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    task_id INTEGER NOT NULL,
    order_position INTEGER DEFAULT '0' NOT NULL,
	user_id INTEGER NOT NULL,
	title VARCHAR2(200 CHAR) NOT NULL,
	description CLOB,
	is_pinned SMALLINT DEFAULT '0' NOT NULL,
	is_hidden SMALLINT DEFAULT '0' NOT NULL,
	is_deleted SMALLINT DEFAULT '0' NOT NULL,
	is_completed SMALLINT DEFAULT '0' NOT NULL,
	deleted_at TIMESTAMP,
	expires_at TIMESTAMP,
	created_at TIMESTAMP NOT NULL,
	updated_at TIMESTAMP NOT NULL,
	PRIMARY KEY (subtask_id),
	FOREIGN KEY(task_id) REFERENCES tb_tasks (task_id) ON DELETE CASCADE,
	FOREIGN KEY(user_id) REFERENCES tb_users (user_id) ON DELETE CASCADE,
	CHECK (is_pinned IN (0, 1)),
	CHECK (is_hidden IN (0, 1)),
	CHECK (is_deleted IN (0, 1)),
	CHECK (is_completed IN (0, 1))
);

CREATE INDEX tb_subtasks_task_idx ON tb_subtasks (task_id, order_position);

CREATE TABLE tb_reminders (
    reminder_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    task_id INTEGER,
    subtask_id INTEGER,
    reminder_date TIMESTAMP NOT NULL,
    email VARCHAR2(254 CHAR) NOT NULL,
    is_sent SMALLINT DEFAULT '0' NOT NULL,
	sent_at TIMESTAMP,
	PRIMARY KEY (reminder_id),
	CONSTRAINT tb_reminder_parent_ck CHECK ((task_id IS NOT NULL AND subtask_id IS NULL) OR (task_id IS NULL AND subtask_id IS NOT NULL)),
	UNIQUE (task_id),
	FOREIGN KEY(task_id) REFERENCES tb_tasks (task_id) ON DELETE CASCADE,
	UNIQUE (subtask_id),
	FOREIGN KEY(subtask_id) REFERENCES tb_subtasks (subtask_id) ON DELETE CASCADE,
	CHECK (is_sent IN (0, 1))
);
